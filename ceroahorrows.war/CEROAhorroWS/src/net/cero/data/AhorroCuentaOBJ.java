package net.cero.data;

public class AhorroCuentaOBJ {
	private String cuenta;
	private String clabe;
	private String folioContrato;
	
	/**
	 * @return the cuenta
	 */
	public String getCuenta() {
		return cuenta;
	}
	/**
	 * @param cuenta the cuenta to set
	 */
	public void setCuenta(String cuenta) {
		this.cuenta = cuenta;
	}
	/**
	 * @return the clabe
	 */
	public String getClabe() {
		return clabe;
	}
	/**
	 * @param clabe the clabe to set
	 */
	public void setClabe(String clabe) {
		this.clabe = clabe;
	}
	/**
	 * @return the folioContrato
	 */
	public String getFolioContrato() {
		return folioContrato;
	}
	/**
	 * @param folioContrato the folioContrato to set
	 */
	public void setFolioContrato(String folioContrato) {
		this.folioContrato = folioContrato;
	}
	
	
}
