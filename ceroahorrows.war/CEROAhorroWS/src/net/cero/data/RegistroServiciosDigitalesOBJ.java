package net.cero.data;

public class RegistroServiciosDigitalesOBJ {
	private Integer id;
	private String cuenta;
	private String usuario;
	private String password;
	private String folioContrato;
	private Integer estatus;
	private String nombreDocumento;
	private String alfrescoId;
	private Integer tipoArchivoId;
	
	
	public Integer getId() {
		return id;
	}
	public void setId(Integer id) {
		this.id = id;
	}
	public String getCuenta() {
		return cuenta;
	}
	public void setCuenta(String cuenta) {
		this.cuenta = cuenta;
	}
	public String getUsuario() {
		return usuario;
	}
	public void setUsuario(String usuario) {
		this.usuario = usuario;
	}
	public String getPassword() {
		return password;
	}
	public void setPassword(String password) {
		this.password = password;
	}
	public String getFolioContrato() {
		return folioContrato;
	}
	public void setFolioContrato(String folioContrato) {
		this.folioContrato = folioContrato;
	}
	public Integer getEstatus() {
		return estatus;
	}
	public void setEstatus(Integer estatus) {
		this.estatus = estatus;
	}
	public String getNombreDocumento() {
		return nombreDocumento;
	}
	public void setNombreDocumento(String nombreDocumento) {
		this.nombreDocumento = nombreDocumento;
	}
	public String getAlfrescoId() {
		return alfrescoId;
	}
	public void setAlfrescoId(String alfrescoId) {
		this.alfrescoId = alfrescoId;
	}
	public Integer getTipoArchivoId() {
		return tipoArchivoId;
	}
	public void setTipoArchivoId(Integer tipoArchivoId) {
		this.tipoArchivoId = tipoArchivoId;
	}
	
}
