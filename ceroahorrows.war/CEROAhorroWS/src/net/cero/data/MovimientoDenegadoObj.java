package net.cero.data;

public class MovimientoDenegadoObj {

	private int tarjeta;
	private String tipoMedioAcceso;
	private String medioAcceso;
	private String fechaInicial;
	private String fechaFinal;
	public int getTarjeta() {
		return tarjeta;
	}
	public void setTarjeta(int tarjeta) {
		this.tarjeta = tarjeta;
	}
	public String getTipoMedioAcceso() {
		return tipoMedioAcceso;
	}
	public void setTipoMedioAcceso(String tipoMedioAcceso) {
		this.tipoMedioAcceso = tipoMedioAcceso;
	}
	public String getMedioAcceso() {
		return medioAcceso;
	}
	public void setMedioAcceso(String medioAcceso) {
		this.medioAcceso = medioAcceso;
	}
	public String getFechaInicial() {
		return fechaInicial;
	}
	public void setFechaInicial(String fechaInicial) {
		this.fechaInicial = fechaInicial;
	}
	public String getFechaFinal() {
		return fechaFinal;
	}
	public void setFechaFinal(String fechaFinal) {
		this.fechaFinal = fechaFinal;
	}
	
	
}
